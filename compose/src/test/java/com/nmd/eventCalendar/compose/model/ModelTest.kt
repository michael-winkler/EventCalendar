package com.nmd.eventCalendar.compose.model

import androidx.compose.ui.graphics.Color
import kotlinx.datetime.LocalDate
import kotlinx.datetime.Month
import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class ModelTest {

    private fun event(
        date: LocalDate,
        endDate: LocalDate? = null,
        shape: Color = Color.Blue,
        text: Color = Color.White
    ) = Event(date = date, name = "E", shapeColor = shape, textColor = text, endDate = endDate)

    // --- Event -------------------------------------------------------------------------------

    @Test
    fun singleDayEventCoversOnlyItsDate() {
        val e = event(LocalDate(2026, 3, 10))
        assertEquals(LocalDate(2026, 3, 10), e.lastDate)
        assertEquals(1, e.spanDays)
        assertFalse(e.isMultiDay)
        assertTrue(e.occursOn(LocalDate(2026, 3, 10)))
        assertFalse(e.occursOn(LocalDate(2026, 3, 11)))
    }

    @Test
    fun multiDayEventCoversItsWholeInclusiveRange() {
        val e = event(LocalDate(2026, 2, 27), endDate = LocalDate(2026, 3, 2))
        assertTrue(e.isMultiDay)
        assertEquals(4, e.spanDays) // 27, 28 Feb, 1, 2 Mar (2026 is not a leap year)
        assertTrue(e.occursOn(LocalDate(2026, 2, 27)))
        assertTrue(e.occursOn(LocalDate(2026, 3, 2)))
        assertFalse(e.occursOn(LocalDate(2026, 2, 26)))
        assertFalse(e.occursOn(LocalDate(2026, 3, 3)))
    }

    @Test
    fun endDateBeforeStartIsTreatedAsSingleDay() {
        val e = event(LocalDate(2026, 3, 10), endDate = LocalDate(2026, 3, 1))
        assertEquals(LocalDate(2026, 3, 10), e.lastDate)
        assertEquals(1, e.spanDays)
        assertFalse(e.isMultiDay)
    }

    @Test
    fun autoGeneratedIdsAreUnique() {
        val ids = (1..1_000).map { event(LocalDate(2026, 1, 1)).id }
        assertEquals(ids.size, ids.toSet().size)
    }

    @Test
    fun copyKeepsTheIdButIsADifferentEvent() {
        val a = event(LocalDate(2026, 1, 1))
        val b = a.copy(date = LocalDate(2026, 1, 2))
        assertEquals(a.id, b.id)
        assertNotEquals(a, b)
    }

    @Test
    fun lightBackgroundGetsDarkTextAutomatically() {
        assertEquals(Color.Black, event(LocalDate(2026, 1, 1), shape = Color.Yellow, text = Color.White).effectiveTextColor)
        assertEquals(Color.White, event(LocalDate(2026, 1, 1), shape = Color.Blue, text = Color.White).effectiveTextColor)
        val noAuto = Event(LocalDate(2026, 1, 1), "E", Color.Yellow, Color.White, autoAdjustTextColorForBackground = false)
        assertEquals(Color.White, noAuto.effectiveTextColor)
    }

    @Test
    fun eventSurvivesJsonRoundTrip() {
        val e = Event(
            date = LocalDate(2026, 5, 1),
            name = "Feiertag",
            shapeColor = Color(0xFF43A047),
            textColor = Color.White,
            timeRange = EventTimeRange(8, 0, 9, 15),
            endDate = LocalDate(2026, 5, 2),
            id = 42
        )
        val decoded = Json.decodeFromString(Event.serializer(), Json.encodeToString(Event.serializer(), e))
        assertEquals(e, decoded)
    }

    // --- EventTimeRange ----------------------------------------------------------------------

    @Test
    fun timeRangeContainsIsHalfOpen() {
        val r = EventTimeRange(9, 0, 10, 0)
        assertTrue(r.contains(9, 0))
        assertTrue(r.contains(9, 59))
        assertFalse(r.contains(10, 0))
        assertFalse(r.contains(8, 59))
    }

    @Test
    fun touchingRangesDoNotOverlap() {
        val a = EventTimeRange(9, 0, 10, 0)
        assertFalse(a.overlapsWith(EventTimeRange(10, 0, 11, 0)))
        assertTrue(a.overlapsWith(EventTimeRange(9, 30, 10, 30)))
        assertTrue(a.overlapsWith(EventTimeRange(8, 0, 12, 0)))
    }

    @Test
    fun durationAndValidity() {
        assertEquals(90, EventTimeRange(9, 0, 10, 30).getDurationMinutes())
        assertTrue(EventTimeRange(9, 0, 9, 1).isValid())
        assertFalse(EventTimeRange(9, 0, 9, 0).isValid())
        assertFalse(EventTimeRange(10, 0, 9, 0).isValid())
    }

    // --- YearMonth ---------------------------------------------------------------------------

    @Test
    fun plusMonthsRollsOverYears() {
        assertEquals(YearMonth(2027, Month.JANUARY), YearMonth(2026, Month.DECEMBER).plusMonths(1))
        assertEquals(YearMonth(2025, Month.DECEMBER), YearMonth(2026, Month.JANUARY).minusMonths(1))
        assertEquals(YearMonth(2031, Month.MARCH), YearMonth(2026, Month.MARCH).plusMonths(60))
        assertEquals(YearMonth(2021, Month.MARCH), YearMonth(2026, Month.MARCH).minusMonths(60))
    }

    @Test
    fun yearMonthOrdering() {
        assertTrue(YearMonth(2026, Month.JANUARY) < YearMonth(2026, Month.FEBRUARY))
        assertTrue(YearMonth(2025, Month.DECEMBER) < YearMonth(2026, Month.JANUARY))
        assertEquals(0, YearMonth(2026, Month.MAY).compareTo(YearMonth.from(LocalDate(2026, 5, 31))))
    }
}
